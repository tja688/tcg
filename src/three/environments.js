export function resolveArenaEnv({ floor = 0, kind = 'combat' } = {}) {
  if (kind === 'boss') return 'abyss';
  if (kind === 'title') return 'dusk';
  const f = Number(floor) || 0;
  if (f >= 10) return kind === 'elite' ? 'abyss' : 'threshold';
  if (f >= 6) return kind === 'elite' ? 'threshold' : 'void';
  if (f >= 3) return kind === 'elite' ? 'void' : 'ashen';
  return kind === 'elite' ? 'ashen' : 'dusk';
}
